const { chromium, expect } = require('../../../../../frontend/node_modules/@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const report = { version: 'M002-UI-04', checks: [], routes: [], errors: [], scope: 'Local simulated prototype only; no service authentication or deletion verification.' };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const p = await ctx.newPage();
  p.on('pageerror', e => report.errors.push(e.message));
  const visit = async (route, query = '') => {
    await p.goto('http://127.0.0.1:4174/prototype/?page=' + route + '&lang=zh&v=M002-UI-04' + query);
    await expect(p.locator('h1')).toBeVisible();
    await p.waitForTimeout(260);
  };
  const click = a => p.locator('[data-action="' + a + '"]:visible').first().click();
  await visit('login', '&role=guest');
  await p.fill('#auth-username', 'learner');
  await p.fill('#auth-password', 'example-pass');
  await p.locator('#auth-password').press('Enter');
  await expect(p.locator('.account-dropdown')).toBeVisible();
  report.checks.push({ name: 'Auth form Enter submits successfully', status: 'PASS' });
  await visit('profile', '&role=learner');
  await click('delete-account');
  await p.fill('#delete-password', 'example-pass');
  await p.check('#delete-understood');
  await click('identity-delete-check');
  await click('identity-delete-final');
  await expect(p.locator('.account-dropdown')).toHaveCount(0);
  const saved = await p.evaluate(() => JSON.parse(sessionStorage.getItem('ww-m002-learning-ui04')));
  expect(saved.batches).toEqual([]);
  expect(saved.sessions).toEqual({});
  expect(saved.mastered).toEqual([]);
  expect(saved.generated).toBe(0);
  report.checks.push({ name: 'Confirmed demo deletion clears simulated learning state and exits', status: 'PASS' });
  for (const route of ['adminhome', 'metrics', 'models', 'plans', 'users', 'operations', 'presets', 'messages', 'profile', 'growth', 'bag', 'shop']) {
    await visit(route, '&role=learner');
    const overflow = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    expect(overflow).toBe(false);
    if (['adminhome', 'metrics', 'models', 'plans', 'users', 'operations', 'presets', 'messages'].includes(route)) await expect(p.locator('.admin-nav a')).toHaveCount(8);
    report.routes.push({ route, status: 'PASS', overflow });
  }
  report.checks.push({ name: 'Eight admin modules and four account views render with the revised shared shell', status: 'PASS' });
  await ctx.close();
  const c2 = await browser.newContext({ viewport: { width: 390, height: 900 } });
  const q = await c2.newPage();
  await q.goto('http://127.0.0.1:4174/prototype/?page=review&batch=b3&lang=zh&role=learner&v=M002-UI-04');
  await expect(q.locator('.slot').first()).toBeVisible();
  await q.screenshot({ path: path.join(__dirname, 'UI04-multiword-390.png'), fullPage: true });
  for (let i = 0; i < 2; i++) await q.locator('[data-action="learn-skip"]').click();
  await expect(q.locator('[data-gap="0"]')).toBeVisible();
  await q.screenshot({ path: path.join(__dirname, 'UI04-passage-390.png'), fullPage: true });
  await q.locator('[data-action="learn-overview"]').first().click();
  await q.locator('[data-action="learn-submit"]').click();
  await expect(q.locator('s.bad').first()).toBeVisible();
  await q.screenshot({ path: path.join(__dirname, 'UI04-summary-390.png'), fullPage: true });
  report.checks.push({ name: 'Mobile multiword, anonymous passage and submitted corrections are captured', status: 'PASS' });
  await c2.close(); await browser.close();
  expect(report.errors).toEqual([]);
  report.status = 'PASS';
  fs.writeFileSync(path.join(__dirname, 'ui04-followup-results.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report));
})().catch(e => { report.status = 'FAIL'; report.error = e.message; fs.writeFileSync(path.join(__dirname, 'ui04-followup-results.json'), JSON.stringify(report, null, 2) + '\n'); console.error(e); process.exit(1); });
